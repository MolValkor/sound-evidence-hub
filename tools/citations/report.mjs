// Render checker results as Markdown (for humans / PR comments) and a compact JSON
// status file the site can import (e.g. "39 sources checked on <date>").

import { WEAK_MAX } from './lib.mjs';

const ICON = { ok: '✅', redirect: '↪️', dead: '❌', retracted: '⛔', 'retracted-labelled': '🏷️', mismatch: '⚠️', unverified: '❔' };
const esc = (s) => String(s ?? '').replace(/\|/g, '\\|').replace(/\n/g, ' ');

export function renderMarkdown(run, { checkedAt }) {
  const s = run.summary;
  const L = [];
  L.push('# Citation check report', '');
  L.push(`Generated by \`npm run check:citations\` on **${checkedAt}**. Do not edit by hand.`, '');
  L.push('## Summary', '');
  L.push('| Result | Count |', '|---|---|');
  L.push(`| Citations checked | ${s.citations} |`);
  L.push(`| ✅ OK | ${s.ok} |`);
  L.push(`| ↪️ Permanent redirect (update URL) | ${s.redirect} |`);
  L.push(`| ❌ Dead link | ${s.dead} |`);
  L.push(`| ⛔ Retracted (total) | ${s.retracted} |`);
  L.push(`| ⛔ … of which not yet labelled on the site (fails the run) | ${s.retractedUnlabelled} |`);
  L.push(`| ⚠️ Metadata mismatch (DOI/PMID may point at a different paper) | ${s.mismatch} |`);
  L.push(`| ❔ Unverified this run (timeouts / 5xx) | ${s.unverified} |`);
  L.push(`| Expressions of concern | ${s.concerns} |`);
  L.push(`| Citations with a published correction/erratum | ${s.corrections} |`);
  L.push(`| Superseded by a newer version (e.g. Cochrane update) | ${s.superseded} |`);
  L.push(`| Weak-design citations (strength ≤ ${WEAK_MAX}) | ${s.weakCitations} |`);
  L.push(`| Claims resting only on weak designs | ${s.weakClaims} |`);
  L.push(`| Claims rated strong/moderate on weak designs only (overrated) | ${s.overratedClaims} |`);
  L.push(`| Other linked sources (study cards, news) | ${s.extraLinks} (dead: ${s.extraDead}) |`);
  L.push(`| DOI landing pages that refuse scripts (DOI itself confirmed registered) | ${s.landingBlocked} |`);
  if (s.missingRefs) L.push(`| Topic references to missing citation ids | ${s.missingRefs} |`);
  L.push('');
  L.push("The run **fails** (exit 1) on dead links, retractions the site doesn't label yet, metadata mismatches or missing citation ids. `--strict` also fails on overrated claims, unverified links and redirects.", '');

  const problems = run.results.filter((r) => r.verdict !== 'ok');
  L.push('## Needs attention', '');
  if (!problems.length) L.push('Nothing. Every citation resolved and matched its metadata.', '');
  for (const r of problems) {
    L.push(`### ${ICON[r.verdict]} \`${r.id}\` — ${r.verdict}`, '');
    L.push(`${esc(r.authors)} (${r.year}). ${esc(r.title)}`, '');
    if (r.verdict === 'retracted-labelled') L.push('Labelled as retracted on the site (`retraction` field in `src/data/citations.ts`) and excluded from evidence grading.', '');
    for (const l of r.links.filter((l) => l.status !== 'ok')) L.push(`- **${l.kind}** ${l.url}: ${l.status}. ${esc(l.detail)}${l.canonical ? ` → canonical: ${l.canonical}` : ''}`);
    for (const i of r.issues.filter((i) => i.level !== 'info')) L.push(`- **${i.source}** ${i.level}: ${esc(i.message)}`);
    for (const n of r.notices.notices) L.push(`- **notice** ${n.status} (${n.type}${n.doi ? `, ${n.doi}` : ''}, via ${n.source}${n.date ? `, ${n.date}` : ''})`);
    L.push('');
  }

  const notes = run.results.filter((r) => r.verdict === 'ok' && (r.issues.length || r.notices.notices.length));
  if (notes.length) {
    L.push('## Notes on passing citations', '');
    for (const r of notes) {
      for (const i of r.issues) L.push(`- \`${r.id}\` (${i.source}${i.level === 'info' ? ', info' : ''}): ${esc(i.message)}`);
      for (const n of r.notices.notices.filter((n) => n.status === 'superseded')) L.push(`- \`${r.id}\`: a **newer version** exists ([${n.doi}](https://doi.org/${n.doi})${n.date ? `, ${n.date}` : ''}). Check whether its conclusions differ before relying on this version.`);
      for (const n of r.notices.notices.filter((n) => n.status !== 'superseded')) L.push(`- \`${r.id}\`: has a published **${n.type}**${n.doi ? ` ([${n.doi}](https://doi.org/${n.doi}))` : ''}${n.date ? ` dated ${n.date}` : ''}, via ${n.source}. Not a retraction; check the correction doesn't change numbers quoted on the site.`);
    }
    L.push('');
  }

  L.push('## Claims by evidence design', '');
  L.push('Design strength is a coarse cross-check, **not** a quality score: a systematic review of high-risk-of-bias trials still counts as a review here. Topic ratings are set by a person after reading the sources; this table only flags ratings that look out of line with the designs behind them.', '');
  L.push('| Claim | Site rating | Strongest design | Review-level sources | Check |', '|---|---|---|---|---|');
  for (const t of run.topics) {
    const strongest = t.strongestLabel ?? '—';
    const flag = { ok: '✅ consistent', 'weak-only': '🟡 weak evidence only (rating reflects it)', overrated: '❌ overrated', 'thin-strong': '⚠️ thin for "strong"' }[t.status];
    L.push(`| ${esc(t.title)} | ${t.rating} | ${t.maxStrength === null ? 'none' : `${strongest} (${t.maxStrength})`} | ${t.reviewLevelSources} | ${flag} |`);
  }
  L.push('');

  L.push('## All citations', '');
  L.push('| | Id | Year | Design (strength) | DOI | PMID | Notes |', '|---|---|---|---|---|---|---|');
  for (const r of run.results) {
    const note = [
      ...r.issues.filter((i) => i.level === 'warn').map((i) => i.code),
      ...r.notices.notices.map((n) => n.type),
      ...r.links.filter((l) => l.kind === 'url').map((l) => `url ${l.status}`),
    ].join(', ');
    L.push(`| ${ICON[r.verdict]} | \`${r.id}\` | ${r.year} | ${esc(r.grade.label)}${r.grade.strength === null ? '' : ` (${r.grade.strength})`} | ${r.doi ? `[${esc(r.doi)}](https://doi.org/${r.doi})` : '—'} | ${r.pmid ? `[${r.pmid}](https://pubmed.ncbi.nlm.nih.gov/${r.pmid}/)` : '—'} | ${esc(note)} |`);
  }
  L.push('');

  if (run.extraLinks.length) {
    L.push('## Other linked sources (study cards & news)', '');
    L.push('| Status | File | Link |', '|---|---|---|');
    for (const e of run.extraLinks) L.push(`| ${e.status} | ${esc(e.where)} | ${esc(e.url ?? e.doi)}${e.status !== 'ok' ? ` — ${esc(e.detail)}` : ''} |`);
    L.push('');
  }
  if (run.unusedCitations.length) L.push(`Citations not referenced by any topic: ${run.unusedCitations.map((x) => `\`${x}\``).join(', ')}`, '');
  return L.join('\n');
}

export function renderJson(run, { checkedAt }) {
  return {
    checkedAt,
    summary: run.summary,
    topics: run.topics,
    citations: run.results.map((r) => ({
      id: r.id, verdict: r.verdict, year: r.year, title: r.title, doi: r.doi, pmid: r.pmid, pmcid: r.pmcid, url: r.url,
      design: r.grade.design, designLabel: r.grade.label, strength: r.grade.strength, designBasis: r.grade.basis,
      links: r.links.map(({ chain, ...l }) => l), issues: r.issues, notices: r.notices.notices,
    })),
    extraLinks: run.extraLinks,
    missingRefs: run.missingRefs,
    unusedCitations: run.unusedCitations,
  };
}

/** Tiny public status object the site can import without shipping the full report. */
export function renderStatus(run, { checkedAt }) {
  const s = run.summary;
  return { checkedAt, citations: s.citations, ok: s.ok, redirect: s.redirect, dead: s.dead, retracted: s.retracted, retractedUnlabelled: s.retractedUnlabelled, mismatch: s.mismatch, unverified: s.unverified, corrections: s.corrections, weakClaims: s.weakClaims };
}
